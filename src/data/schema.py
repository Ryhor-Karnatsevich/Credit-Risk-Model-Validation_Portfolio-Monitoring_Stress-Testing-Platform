def get_headers(kind):
    """Return a fresh column list, shared by all annual readers."""
    columns = {"orig": ORIGINATION_COLUMNS, "perf": PERFORMANCE_COLUMNS}[kind]
    if len(columns) != len(set(columns)):
        raise ValueError(f"Duplicate column names in {kind} schema")
    return list(columns)
